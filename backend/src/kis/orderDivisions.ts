/**
 * 국내주식 주문구분(`ORD_DVSN`) 코드.
 *
 * **확인된 것과 아닌 것을 값으로 가른다.** 이 레포는 짐작한 값을 코드에 넣지
 * 않는다(CLAUDE.md). 그런데 주문구분은 짐작이 특히 위험하다 — 틀린 코드로
 * 주문이 나가면 거절되는 데서 끝나지 않고, **다른 뜻으로 접수될 수** 있다.
 *
 * ── 어디까지 확인했나 (2026-08-03) ────────────────────────────────────────
 *
 * 출처는 KIS 공식 저장소 `koreainvestment/open-trading-api`,
 * `legacy/Sample01/kis_domstk.py`다.
 *
 *   54·113행  주문구분 00:지정가, 01:시장가, 02:조건부지정가  **나머지주문구분 API 문서 참조**
 *   376행     00 : 지정가, 01 : 시장가, 02 : 조건부지정가, 03 : 최유리지정가
 *   454·528행 00:지정가, 01:시장가, 02:조건부지정가, **05 : 장전 시간외**
 *   715행     주문단가 … * **장전 시간외, 장후 시간외**, 시장가의 경우 … "0"으로 입력 권고
 *
 * 715행이 **장후 시간외가 존재한다는 것**과 **단가를 0으로 보낸다는 것**까지는
 * 말해 준다. 그런데 그 코드값은 이 저장소 어디에도 없다 — 공식 주석이 스스로
 * "나머지는 API 문서 참조"라고 미룬다. 그 문서는 포털 안에 있고 가져오지 못했다.
 *
 * ── 읽기 전용으로 알아내려다 실패했다 ────────────────────────────────────
 *
 * 매수가능조회(`inquire-psbl-order`)가 `ORD_DVSN`을 받으므로 모르는 코드를
 * 넣어 거절되는지 보면 되겠다고 생각했다. **안 된다** — 대조군으로 넣은 `99`도
 * 정상 응답했다(`probeOrderDivisions.ts` 실측). 그 조회는 주문구분을 검증하지
 * 않고 무시한다. 대조군이 없었다면 "05·06·07 전부 유효"라고 잘못 적을 뻔했다.
 *
 * **남은 확인 방법은 실제 주문 한 건뿐이다.** 모의계좌에서 한 번 내 보면
 * 접수되는지 거절되는지 즉시 안다.
 */

/** 이 값이 무엇인지 **확인된** 코드. 주문 경로에 그대로 써도 된다. */
export const CONFIRMED_ORDER_DIVISIONS = {
  /** 지정가. 이 레포가 실주문으로 확인했다 */
  limit: '00',
  /** 시장가. 이 레포가 실주문으로 확인했다 */
  market: '01',
  /**
   * 장전 시간외(08:30~08:40). KIS 공식 예제가 두 곳에서 그렇게 적는다.
   * **아직 이 레포가 주문으로 확인하지는 않았다** — 문서 근거만 있다.
   */
  preMarketClose: '05',
} as const;

/**
 * 값을 **모르는** 주문구분. 이름만 알고 코드는 확인되지 않았다.
 *
 * 여기 있는 것을 주문 경로에 넣지 마라. 넣으려면 먼저 모의계좌에서 한 건
 * 내 보고 결과를 이 파일에 적어라 — 그러면 위 표로 올라간다.
 */
export const UNCONFIRMED_ORDER_DIVISIONS = [
  '장후 시간외 종가 (15:40~16:00) — 존재와 "단가 0" 규칙은 확인, 코드값 미확인',
  '시간외 단일가 (16:00~18:00) — 코드값 미확인',
] as const;

export type ConfirmedOrderDivision =
  (typeof CONFIRMED_ORDER_DIVISIONS)[keyof typeof CONFIRMED_ORDER_DIVISIONS];

/**
 * 이 주문구분이 단가를 비워야 하는가.
 *
 * 공식 예제 715행: *"장전 시간외, 장후 시간외, 시장가의 경우 1주당 가격을
 * 공란으로 비우지 않음 `0`으로 입력 권고"*. 빈 문자열이 아니라 **문자열 `'0'`**이다.
 */
export function usesZeroPrice(division: string): boolean {
  return division === CONFIRMED_ORDER_DIVISIONS.market
    || division === CONFIRMED_ORDER_DIVISIONS.preMarketClose;
}
