/**
 * **판단자를 부를 것인가.** 적정가 표를 받아 소집 여부만 정한다.
 *
 * ── 왜 파일로 뺐나 (2026-09-03) ─────────────────────────────────────────
 *
 * 이 판정이 `analyzeFairValue.ts` 안에 있었고 **시험이 하나도 없었다.** 그날
 * 후보 발굴을 넣자마자 게이트가 통째로 무너졌는데, 무너진 것을 코드가 아니라
 * **하트비트 로그를 눈으로 읽어서** 알았다 — 판단자가 하루 13번 불려 11번이
 * 결정 0건이었다.
 *
 * 스크립트 파일은 `main()`을 끝에서 부르므로 import만 해도 실행된다. 그래서
 * 시험을 붙이려면 순수 로직이 밖에 있어야 한다.
 *
 * ── 두 문 ────────────────────────────────────────────────────────────────
 *
 * ① **문턱을 넘었나** — 싸거나(보유·후보 둘 다) 비싸거나(**보유만**)
 * ② **직전과 다른 신호인가** — 같으면 5분 전과 상황이 같다는 뜻이다
 */

/** 이보다 싸면 살 것이 있는지 본다 */
export const CHEAP_GATE = -0.07;
/** 이보다 비싸면 팔 것이 있는지 본다 */
export const RICH_GATE = 0.15;
/**
 * 시그니처를 이 폭으로 칸 나눈다.
 *
 * ★★ **1%p 단위로 적었더니 게이트가 헛돌았다.** gap이 −9%↔−10%를 오가기만 해도
 *    "새 신호"가 되어 2026-09-03 10:35~10:55에 5분마다 다섯 번을 불렀다.
 *    같은 상황을 다섯 번 산 것이다.
 */
export const SIGNATURE_BUCKET = 0.05;

export interface GateInput {
  symbol: string;
  /** 적정가 대비. 못 냈으면 null */
  gap: number | null;
  /** 들고 있는가 */
  held: boolean;
  /**
   * 시장 대비 60일로 **급락 중인가**(`fairValue.isFalling`). 모르면 `false`.
   *
   * ★ 호출부가 안 주면 예전 동작 그대로다 — 이 필드를 안 넘기는 곳이 조용히
   *   달라지지 않게 옵셔널로 둔다.
   */
  falling?: boolean;
}

/**
 * 이 종목이 판단자를 부를 이유가 되는가.
 *
 * ★★ **"비싸다"는 들고 있을 때만 뜻이 있다.** 안 들고 있는 종목이 비싼 것은
 *    아무 행동도 낳지 않는다 — 우리는 공매도를 하지 않는다. 팔려면 들고
 *    있어야 하고, 후보가 비싸면 그냥 안 사면 되는 일이다.
 *
 *    이것을 빼먹어 2026-09-03에 후보 13종목이 죄다 비싸다는 이유로
 *    (금호건설 +145%, JW신약 +94%) 매 회차 판단자를 불렀다.
 *
 * ★★ **"떨어졌다"도 후보를 부를 이유가 아니다** (2026-09-10).
 *
 * 급락 축(`isFalling`)은 2026-09-03에 사용자가 *"급락 종목 걸러내는 축
 * 추가해줘"*라고 해서 생겼는데, **⭐추천에만 걸리고 이 게이트에는 안 걸려
 * 있었다.** 그래서 적정가가 −7% 아래인 급락 종목이 매 회차 판단자를 불렀고,
 * 판단자는 매번 같은 말로 거절했다 —
 *
 *   *"가장 싼 여섯(코오롱티슈진 −63.4%, HLB −31.3%, 리가켐바이오 −26.5%)은
 *    전부 '크게 떨어졌다'이지 '싸다'가 아니다. 회차 542~595가 같은 이유로
 *    걸렀고 그 판단을 유지한다."* (2026-09-09 회차 596)
 *
 * 모의 시험 6거래일(9/3~9/9)에 회차 125개 중 **116개가 결정 0건**이었다.
 * 헤드리스 Claude를 하루 수십 번 사서 같은 거절을 되풀이한 것이다.
 *
 * ★ **보유 중인 것은 급락해도 부른다.** falling은 *"싸다를 믿지 않는다"*는
 *   축이지 *"보지 말라"*는 축이 아니다 — 들고 있는 종목이 무너지는 중이면
 *   그것이야말로 판단자가 봐야 하는 자리다(팔지 말지를 정해야 한다).
 *   위의 "비싼 것은 보유일 때만"과 같은 종류의 비대칭이다.
 */
export function crossesGate(row: GateInput): boolean {
  if (row.gap === null) return false;
  if (row.gap <= CHEAP_GATE) return row.held || !row.falling;
  return row.held && row.gap >= RICH_GATE;
}

/**
 * 시그니처에 넣을 **후보** 수. 보유는 수에 상관없이 전부 넣는다.
 *
 * ★★ **판단자가 보는 만큼만 접는다** (2026-09-10). 그전에는 문턱을 넘은 것을
 *    전부 접었는데, 후보 풀이 900종목이 되자 문턱을 넘는 것이 163종목이 됐고
 *    **그중 하나만 칸을 옮겨도 새 신호**가 됐다. 그날 실측이 이렇다:
 *
 *      09-08  소집 44 · 서로 다른 신호 27 · 시그니처 117자
 *      09-09  소집 30 · 서로 다른 신호 17 · 시그니처 124자
 *      09-10  소집 31 · 서로 다른 신호 **31** · 시그니처 **1,735자**  ← 방어가 0%
 *
 *    31번을 불러 31번 다 결정 0건이었다. 헤드리스 Claude를 그만큼 산 것이다.
 *
 * ★ 5인 이유는 **판단자 화면의 ⭐가 다섯**이기 때문이다(`RECOMMEND_LIMIT`).
 *   그 아래 25칸은 "판정이 어디쯤에서 끊겼는지 보이는 만큼"이지 살 자리가
 *   아니다 — 100등짜리가 한 칸 움직인 것은 판단을 바꾸지 않는다.
 *
 * ★ **보유는 전부 넣는다.** 들고 있는 것의 gap이 깊어지면 팔지 말지가 바뀐다.
 */
export const SIGNATURE_TOP_CANDIDATES = 5;

/**
 * 문턱을 넘은 것들을 **한 문자열로** 접는다. 직전 회차 것과 같으면 안 부른다.
 *
 * ★ 종목코드로 정렬한다 — 표의 순서가 바뀌었다고 새 신호가 되면 안 된다.
 *
 * ★ 후보는 **싼 순 `SIGNATURE_TOP_CANDIDATES`개만** 넣는다(위 주석).
 */
export function gateSignature(rows: GateInput[]): string {
  const crossed = rows.filter(crossesGate);
  const held = crossed.filter((r) => r.held);
  const candidates = crossed
    .filter((r) => !r.held)
    .sort((a, b) => (a.gap ?? 0) - (b.gap ?? 0))
    .slice(0, SIGNATURE_TOP_CANDIDATES);
  return [...held, ...candidates]
    .map((r) => `${r.symbol}:${Math.round((r.gap ?? 0) / SIGNATURE_BUCKET)}`)
    .sort()
    .join(',');
}
