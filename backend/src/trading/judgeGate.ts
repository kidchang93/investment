/**
 * **판단자를 부를 것인가.** 적정가 표를 받아 소집 여부만 정한다.
 *
 * ── 왜 파일로 뺐나 (2026-09-03) ─────────────────────────────────────────
 *
 * 이 판정이 `analyzeFairValue.ts` 안에 있었고 **시험이 하나도 없었다.** 그날
 * 후보 발굴을 넣자마자 게이트가 통째로 무너졌는데, 무너진 것을 코드가 아니라
 * **하트비트 로그를 눈으로 읽어서** 알았다 — 판단자가 하루 13번 불려 11번이
 * 결정 0건이었다.
 *
 * 스크립트 파일은 `main()`을 끝에서 부르므로 import만 해도 실행된다. 그래서
 * 시험을 붙이려면 순수 로직이 밖에 있어야 한다.
 *
 * ── 두 문 ────────────────────────────────────────────────────────────────
 *
 * ① **문턱을 넘었나** — 싸거나(보유·후보 둘 다) 비싸거나(**보유만**)
 * ② **직전과 다른 신호인가** — 같으면 5분 전과 상황이 같다는 뜻이다
 */

/** 이보다 싸면 살 것이 있는지 본다 */
export const CHEAP_GATE = -0.07;
/** 이보다 비싸면 팔 것이 있는지 본다 */
export const RICH_GATE = 0.15;
/**
 * 시그니처를 이 폭으로 칸 나눈다.
 *
 * ★★ **1%p 단위로 적었더니 게이트가 헛돌았다.** gap이 −9%↔−10%를 오가기만 해도
 *    "새 신호"가 되어 2026-09-03 10:35~10:55에 5분마다 다섯 번을 불렀다.
 *    같은 상황을 다섯 번 산 것이다.
 */
export const SIGNATURE_BUCKET = 0.05;

export interface GateInput {
  symbol: string;
  /** 적정가 대비. 못 냈으면 null */
  gap: number | null;
  /** 들고 있는가 */
  held: boolean;
}

/**
 * 이 종목이 판단자를 부를 이유가 되는가.
 *
 * ★★ **"비싸다"는 들고 있을 때만 뜻이 있다.** 안 들고 있는 종목이 비싼 것은
 *    아무 행동도 낳지 않는다 — 우리는 공매도를 하지 않는다. 팔려면 들고
 *    있어야 하고, 후보가 비싸면 그냥 안 사면 되는 일이다.
 *
 *    이것을 빼먹어 2026-09-03에 후보 13종목이 죄다 비싸다는 이유로
 *    (금호건설 +145%, JW신약 +94%) 매 회차 판단자를 불렀다.
 */
export function crossesGate(row: GateInput): boolean {
  if (row.gap === null) return false;
  if (row.gap <= CHEAP_GATE) return true;
  return row.held && row.gap >= RICH_GATE;
}

/**
 * 문턱을 넘은 것들을 **한 문자열로** 접는다. 직전 회차 것과 같으면 안 부른다.
 *
 * ★ 종목코드로 정렬한다 — 표의 순서가 바뀌었다고 새 신호가 되면 안 된다.
 */
export function gateSignature(rows: GateInput[]): string {
  return rows
    .filter(crossesGate)
    .map((r) => `${r.symbol}:${Math.round((r.gap ?? 0) / SIGNATURE_BUCKET)}`)
    .sort()
    .join(',');
}
